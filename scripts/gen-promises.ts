// Writes PROMISES.md from shared/promises.ts so the ledger doc can't drift from the code. Run: npx tsx scripts/gen-promises.ts
import fs from 'node:fs';
import { PROMISES } from '../shared/promises';
const esc = (x: string) => x.replace(/\|/g, '\\|');
const rows = PROMISES.map((p) => `| \`${p.id}\` | ${esc(p.text)} | ${p.tiers.length === 3 ? 'All' : p.tiers.join(', ')} | ${p.sources.join(', ')} | ${p.kind} | ${esc(p.rule)} | ${esc(p.familyScreen)} | ${esc(p.coachAlert)} |`);
fs.writeFileSync('PROMISES.md', `# Promise ledger

Every promise Baller Connection makes, in landing, pricing, FAQ, onboarding and emails, is listed here with:

- **Rule**: what the shared engine does to keep it (\`shared/promises.ts\`, \`shared/engine.ts\`)
- **Family sees it kept**: the screen where the family can check it
- **Coach alert**: what tells staff before it is at risk (the queue shows “Due soon” items, and the sweep sends \`promise_risk\` notifications)

\`tests/promises.test.ts\` has one enforcement test per id. It fails if a promise is added here without one, and it fails if the landing page brings back copy the engine can't keep.
This file is generated by \`npx tsx scripts/gen-promises.ts\`.

| id | Promise | Tiers | Where it's said | Kind | Rule (engine) | Family sees it kept | Coach alert |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

## What v9 changed (older copy history lives in git; tag \`v8-final\` restores the previous version)

### Promises removed, and why
| Removed | Why |
|---|---|
| \`plan-adjust\`, \`rubric-cycle\`, \`tournament-plan\`, \`season-goal-review\` | Admin the coach would rather do when it helps a player than on a schedule. The tools still exist; they are no longer promised. |
| \`overdue-first\`, \`one-cue\`, \`next-rep\`, \`clip-reviewed\` | Internal behavior, not something a family needs to be promised. Merged into \`reply-window\` and the review format. |
| \`every-submission\` | Merged into \`reviews-per-week\` (Inner Circle: every clip). |
| \`message-reply\`, \`game-reply\` | One reply number per plan (\`reply-window\`), for clips and for messages. Games get a coach read, not a promised reply. |
| \`focus-confirm\` | Replaced by \`teach-back\` (optional, in the player's own words, never blocks the next rep). |
| \`confidence-check\` | Replaced by \`stuck-reply\` (the player asks) plus a coach-only “check in” prompt after two rougher games. Never a clinical claim. |
| \`payment-grace\`, \`spot-offer\` | Billing mechanics (still built, still dormant). Not marketing promises. |

### Promises added
| Added | Why |
|---|---|
| \`first-look\` | The coach relationship starts with “here is what I saw in you”, in writing, within 2 business days of setup. |
| \`teach-back\` | Replaces tap-to-confirm: the player says the adjustment in their own words and the coach marks it. |
| \`stuck-reply\` | A private note to the coach on every player screen, with a human reply inside the plan's window. |

### Copy changed
| Was | Now | Why |
|---|---|---|
| Hero: “Make practice show up in games.” | “A coach who sees your reps between sessions.” with “Make practice show up in games” as the outcome line | The method is the product; the outcome is the reason |
| “Practice → game 63%”, “transfer rate”, “focus in games” % | Removed. A game note (what carried over, what didn't) and a coach mark: carried over / partly / not yet | A percentage from a few self-reports isn't evidence |
| Habit streaks, levels, badges, confetti, “Level up!” | Off by default. A player can turn on streaks in Progress | Accountability is the coach seeing reps, not a score |
| “Tap each set”, “Submit to coach”, “Got it, I'll do this” | Clip first, one honest sentence, a sets stepper, “Send to my coach”, and “Say it in my words” | Respect for 11 to 15 year olds; no homework tone |
| Auto-written coach “welcome” message | Removed. The first message is the coach's own first look | It looked coach-written but wasn't |
| Per-rep notifications to parents | Off by default; Sunday note plus timeline. A parent can opt in | Parents shouldn't be pulled into every rep |
| Plans page: plan adjusted every 2 weeks, rubric, tournament plan, season goal review | Removed from the comparison table | They are not promises a coach can keep on a schedule |
| Fit | “Good fit / not a fit” on Plans and at the end of Apply; the application asks the player for their own words; parent-only applications are flagged for the coach, not rejected | Honest about who this is for |
`);
